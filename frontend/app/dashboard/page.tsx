"use client";
import { useState, useCallback, useRef } from "react";
import { v4 as uuidv4 } from "uuid";
import { BarChart2, Database, Sparkles, ChevronRight, HelpCircle } from "lucide-react";
import { motion, AnimatePresence } from "framer-motion";

import { ChatInput } from "@/components/chat/ChatInput";
import { ChatHistory } from "@/components/chat/ChatHistory";
import { Dashboard } from "@/components/dashboard/Dashboard";
import { ErrorBanner } from "@/components/ui/ErrorBanner";
import { FileUploadModal } from "@/components/ui/FileUploadModal";
import { AIProgressLoader } from "@/components/ui/AIProgressLoader";
import Preloader from "@/components/ui/Preloader";
import { useToast } from "@/components/ui/Toast";
import { ProfileMenu } from "@/components/ui/ProfileMenu";
import { Text_03 } from "@/components/ui/Text_03";
import dynamic from "next/dynamic";
import { useSession } from "@/hooks/useSession";
import { useAuth } from "@/hooks/useAuth";

const FloatingLines = dynamic(() => import("@/components/ui/FloatingLines"), { ssr: false });
const SplitText = dynamic(() => import("@/components/ui/SplitText"), { ssr: false });
const TextRevealByWord = dynamic(() => import("@/components/ui/TextRevealByWord").then(m => ({ default: m.TextRevealByWord })), { ssr: false });
import { postQuery, createConversation, addConversationTurn } from "@/lib/api";
import type { ChatMessage, DashboardResponse, UploadResponse, ClarificationPayload } from "@/lib/types";

const EXAMPLE_QUERIES = [
  "What is the total revenue generated by each product category?",
  "Show me the monthly revenue trend for each category throughout 2022.",
  "Compare average rating and total revenue for each payment method. Also show overall total revenue.",
  "Which region has the highest average order value?",
];

export default function DashboardPage() {
  const { sessionId, datasourceId, setDatasourceId, resetSession } = useSession();
  const { user, isAuthenticated } = useAuth();
  const { showToast } = useToast();

  const [showPreloader, setShowPreloader] = useState(true);
  const [messages, setMessages] = useState<ChatMessage[]>([]);
  const [dashboards, setDashboards] = useState<DashboardResponse[]>([]); // Store ALL dashboards
  const [activeClarification, setActiveClarification] = useState<ClarificationPayload | null>(null);
  const [isLoading, setIsLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [showUpload, setShowUpload] = useState(false);
  const [sourceName, setSourceName] = useState("Amazon Sales");
  const [uploadColumns, setUploadColumns] = useState<Record<string, string>>({});
  const mainRef = useRef<HTMLElement>(null);

  // Conversation history tracking
  const conversationIdRef = useRef<string | null>(null);

  const handleSend = useCallback(
    async (prompt: string) => {
      if (!sessionId || isLoading) return;
      setError(null);
      setActiveClarification(null);

      setMessages((prev) => [
        ...prev,
        { id: uuidv4(), role: "user", content: prompt, timestamp: new Date() },
      ]);
      setIsLoading(true);

      // Scroll to show loading indicator
      setTimeout(() => {
        mainRef.current?.scrollTo({
          top: mainRef.current.scrollHeight,
          behavior: "smooth",
        });
      }, 100);

      try {
        const result = await postQuery(sessionId, prompt, datasourceId);
        if (result.error) {
          // Only show error in chat - no banner or toast
          setMessages((prev) => [
            ...prev,
            {
              id: uuidv4(),
              role: "assistant",
              content: `I couldn't answer that: ${result.error}`,
              timestamp: new Date(),
            },
          ]);
        } else if (result.clarification) {
          // Ambiguity detected — prompt user with interactive clarification chips
          setActiveClarification(result.clarification);
          setMessages((prev) => [
            ...prev,
            {
              id: uuidv4(),
              role: "assistant",
              content: result.clarification!.question,
              clarification: result.clarification,
              timestamp: new Date(),
            },
          ]);
          showToast("Disambiguation options generated", "info");
        } else {
          setActiveClarification(null);
          // Add new dashboard to array (keep previous ones)
          setDashboards((prev) => [...prev, result]);
          showToast(`"${result.dashboard_title}" ready!`, "success");

          // Scroll to bottom after new dashboard is added
          setTimeout(() => {
            mainRef.current?.scrollTo({
              top: mainRef.current.scrollHeight,
              behavior: "smooth",
            });
          }, 100);

          setMessages((prev) => [
            ...prev,
            {
              id: uuidv4(),
              role: "assistant",
              content: `Here is "${result.dashboard_title}" — ${result.charts.length} chart${result.charts.length !== 1 ? "s" : ""} generated.`,
              warning: result.data_limitations ?? undefined,
              timestamp: new Date(),
            },
          ]);

          // TODO: Enable conversation saving once Supabase is properly configured
          // Save conversation turn if authenticated
          /*
          if (isAuthenticated) {
            console.log("DEBUG: User is authenticated, saving conversation...");
            try {
              // Create conversation on first query
              if (!conversationIdRef.current) {
                console.log("DEBUG: Creating new conversation...");
                const conversation = await createConversation(
                  result.dashboard_title || prompt.slice(0, 50),
                  datasourceId
                );
                console.log("DEBUG: Conversation created:", conversation);
                conversationIdRef.current = conversation.id;
              }

              // Save the turn
              console.log("DEBUG: Adding conversation turn...");
              await addConversationTurn(
                conversationIdRef.current,
                prompt,
                result.sql,
                { charts: result.charts },
                result.insight_summary,
                result.data_limitations
              );
              console.log("DEBUG: Turn saved successfully");
            } catch (saveErr) {
              console.error("DEBUG: Failed to save conversation:", saveErr);
              // Don't show error to user - conversation saving is optional
            }
          } else {
            console.log("DEBUG: User is NOT authenticated, skipping conversation save");
          }
          */
        }
      } catch (e: unknown) {
        const msg =
          e instanceof Error ? e.message : "Connection failed. Is the backend running?";
        setError(msg);
        showToast(msg, "error");
      } finally {
        setIsLoading(false);
      }
    },
    [sessionId, datasourceId, isLoading, showToast, isAuthenticated]
  );

  const handleUpload = (result: UploadResponse) => {
    setDatasourceId(result.datasource_id);
    setSourceName(result.table_name);
    setUploadColumns(result.columns);
    setMessages([]);
    setDashboards([]);  // Clear all dashboards
    setError(null);
    showToast(`"${result.table_name}" loaded — start asking questions!`, "success");
  };

  const handleReset = () => {
    resetSession();
    setMessages([]);
    setDashboards([]);  // Clear all dashboards
    setError(null);
    setSourceName("Amazon Sales");
    setUploadColumns({});
    setDatasourceId("default");
    conversationIdRef.current = null;  // Clear conversation on reset
  };

  const columnNames = Object.keys(uploadColumns);

  return (
    <>
      <AnimatePresence>
        {showPreloader && (
          <Preloader onComplete={() => setShowPreloader(false)} />
        )}
      </AnimatePresence>

      <motion.div
        initial={{ opacity: 0 }}
        animate={{ opacity: showPreloader ? 0 : 1 }}
        transition={{ duration: 0.5 }}
        className="flex h-screen overflow-hidden bg-black text-slate-100 relative"
      >
        {/* FloatingLines — full-screen background */}
        <div className="fixed inset-0" style={{ zIndex: 0 }}>
          <FloatingLines
            enabledWaves={["top", "middle", "bottom"]}
            lineCount={5}
            lineDistance={5}
            bendRadius={5}
            bendStrength={-0.5}
            interactive={true}
            parallax={true}
            linesGradient={["#6366f1", "#818cf8", "#a5b4fc"]}
            animationSpeed={0.8}
            mixBlendMode="screen"
          />
        </div>
        {showUpload && (
          <FileUploadModal
            onClose={() => setShowUpload(false)}
            onUpload={handleUpload}
          />
        )}

        <aside className="relative z-10 w-80 lg:w-96 flex flex-col shrink-0">
          <div className="px-3 pt-3 pb-0 shrink-0 relative z-50">
            {/* Liquid glass floating bar */}
            <div
              style={{
                background: "linear-gradient(145deg, rgba(255,255,255,0.14) 0%, rgba(255,255,255,0.04) 50%, rgba(99,102,241,0.1) 100%)",
                backdropFilter: "blur(28px) saturate(1.8) brightness(1.1)",
                WebkitBackdropFilter: "blur(28px) saturate(1.8) brightness(1.1)",
                borderRadius: "16px",
                boxShadow: [
                  "0 0 0 0.5px rgba(255,255,255,0.2)",
                  "inset 0 1.5px 0 rgba(255,255,255,0.32)",
                  "inset 0 -1px 0 rgba(0,0,0,0.2)",
                  "inset 1px 0 0 rgba(255,255,255,0.1)",
                  "inset -1px 0 0 rgba(255,255,255,0.1)",
                  "0 8px 32px rgba(0,0,0,0.5)",
                  "0 2px 8px rgba(0,0,0,0.3)",
                  "0 0 40px rgba(99,102,241,0.12)",
                ].join(", "),
                padding: "10px 12px",
                overflow: "visible",
              }}
            >
              <div className="flex items-center gap-3 w-full">
                <div className="w-8 h-8 bg-indigo-600 rounded-lg flex items-center justify-center shrink-0">
                  <BarChart2 size={18} />
                </div>
                <div className="flex-1 min-w-0">
                  <h1 className="text-white font-semibold text-sm">Asklytics</h1>
                  <p className="text-slate-500 text-xs flex items-center gap-1 truncate">
                    <Database size={10} />
                    {sourceName}
                  </p>
                </div>
                <ProfileMenu />
              </div>
            </div>
          </div>

          {/* Chat body */}
          <div className="relative flex-1 overflow-hidden flex flex-col">
            {/* Content */}
            <div className="relative flex flex-col h-full" style={{ zIndex: 2 }}>
              {columnNames.length > 0 && (
                <motion.div
                  initial={{ opacity: 0, height: 0 }}
                  animate={{ opacity: 1, height: "auto" }}
                  className="px-4 py-3 border-b border-slate-800 overflow-hidden shrink-0"
                >
                  <p className="text-slate-500 text-xs mb-2">Available columns</p>
                  <div className="flex flex-wrap gap-1">
                    {columnNames.map((col) => (
                      <span
                        key={col}
                        className="bg-slate-800 text-slate-400 text-xs px-2 py-0.5 rounded-full"
                      >
                        {col}
                      </span>
                    ))}
                  </div>
                </motion.div>
              )}

              <ChatHistory messages={messages} isLoading={isLoading} onSelectOption={handleSend} />

              <ChatInput
                onSend={handleSend}
                onUploadClick={() => setShowUpload(true)}
                isLoading={isLoading}
                disabled={!sessionId}
              />
            </div>
          </div>
        </aside>

        <main ref={mainRef} className="relative z-10 flex-1 overflow-y-auto p-6 lg:p-10">
          <div className="flex flex-col min-h-full">
            <AnimatePresence>
              {error && (
                <motion.div
                  initial={{ opacity: 0, y: -8 }}
                  animate={{ opacity: 1, y: 0 }}
                  exit={{ opacity: 0, y: -8 }}
                  className="mb-6"
                >
                  <ErrorBanner message={error} onDismiss={() => setError(null)} />
                </motion.div>
              )}
            </AnimatePresence>

            {/* Interactive Clarification Card on Main Canvas (Upgrade #2) */}
            {activeClarification && !isLoading && (
              <motion.div
                initial={{ opacity: 0, scale: 0.98, y: 12 }}
                animate={{ opacity: 1, scale: 1, y: 0 }}
                className="mb-8 rounded-2xl border border-indigo-500/40 bg-gradient-to-br from-slate-900/90 via-slate-950/90 to-indigo-950/40 p-6 backdrop-blur-xl shadow-2xl"
              >
                <div className="flex items-center gap-2.5 text-indigo-400 mb-2">
                  <div className="p-2 rounded-xl bg-indigo-500/10 border border-indigo-500/20">
                    <Sparkles size={18} className="text-indigo-400 animate-pulse" />
                  </div>
                  <div>
                    <h3 className="text-sm font-semibold text-slate-100">Clarification Needed Before Analysis</h3>
                    <p className="text-xs text-indigo-300/80">Ambiguous business phrasing detected: &ldquo;{activeClarification.matched_term}&rdquo;</p>
                  </div>
                </div>
                <h2 className="text-lg font-medium text-slate-200 mt-3 mb-4">
                  {activeClarification.question}
                </h2>
                <div className="grid grid-cols-1 md:grid-cols-3 gap-3">
                  {activeClarification.options.map((opt, i) => (
                    <button
                      key={i}
                      onClick={() => {
                        setActiveClarification(null);
                        handleSend(opt.refined_prompt);
                      }}
                      className="group flex flex-col justify-between text-left rounded-xl bg-slate-900/80 hover:bg-indigo-950/60 border border-slate-800 hover:border-indigo-500/60 p-4 transition-all duration-200 hover:scale-[1.02] hover:shadow-lg"
                    >
                      <div>
                        <div className="flex items-center justify-between mb-1.5">
                          <span className="text-sm font-semibold text-slate-200 group-hover:text-indigo-300">
                            {opt.label}
                          </span>
                          <ChevronRight size={16} className="text-slate-500 group-hover:text-indigo-400 group-hover:translate-x-1 transition-transform" />
                        </div>
                        <p className="text-xs text-slate-400 group-hover:text-slate-300 font-mono">
                          {opt.subtext}
                        </p>
                      </div>
                      <span className="mt-3 text-[11px] text-indigo-400/80 font-medium opacity-0 group-hover:opacity-100 transition-opacity">
                        Click to generate dashboard &rarr;
                      </span>
                    </button>
                  ))}
                </div>
              </motion.div>
            )}

            {/* Show all dashboards */}
            {dashboards.length > 0 && (
              <div className="space-y-8">
                {dashboards.map((dashboard, index) => (
                  <motion.div
                    key={`${dashboard.dashboard_title}-${index}`}
                    initial={{ opacity: 0, y: 16 }}
                    animate={{ opacity: 1, y: 0 }}
                    transition={{ duration: 0.4, ease: "easeOut" }}
                  >
                    <Dashboard dashboard={dashboard} showSQL onSuggestionClick={handleSend} />
                  </motion.div>
                ))}
              </div>
            )}

            {/* Show loading AFTER existing dashboards - with clear separator */}
            {isLoading && (
              <motion.div
                initial={{ opacity: 0, y: 16 }}
                animate={{ opacity: 1, y: 0 }}
                className={`${dashboards.length > 0 ? "mt-12 pt-8 border-t border-slate-800" : "flex-1 flex items-center justify-center"}`}
              >
                <div className={`${dashboards.length > 0 ? "" : ""}`}>
                  <AIProgressLoader />
                </div>
              </motion.div>
            )}

            {/* Initial empty state */}
            {dashboards.length === 0 && !isLoading && !activeClarification && (
            <motion.div
              initial={{ opacity: 0, y: 12 }}
              animate={{ opacity: 1, y: 0 }}
              transition={{ duration: 0.5 }}
              className="flex flex-col items-center justify-center min-h-[70vh] text-center"
            >
              <div className="w-16 h-16 bg-slate-800 rounded-2xl flex items-center justify-center mb-6">
                <BarChart2 size={32} className="text-slate-600" />
              </div>
              <SplitText
                text="Ask a Business Question"
                className="text-2xl font-semibold text-slate-400 mb-2"
                delay={40}
                duration={0.9}
                ease="power3.out"
                splitType="chars"
                from={{ opacity: 0, y: 40 }}
                to={{ opacity: 1, y: 0 }}
                threshold={0.1}
                rootMargin="0px"
                textAlign="center"
                tag="h2"
              />
              <p className="text-slate-600 max-w-sm text-sm leading-relaxed mb-10">
                Type any question in plain English and get an interactive
                dashboard instantly — no SQL required.
              </p>
              <div className="grid grid-cols-1 sm:grid-cols-2 gap-3 w-full max-w-2xl text-left">
                {EXAMPLE_QUERIES.map((q, i) => (
                  <motion.button
                    key={q}
                    initial={{ opacity: 0, y: 8 }}
                    animate={{ opacity: 1, y: 0 }}
                    whileHover={{ scale: 1.02 }}
                    transition={{ delay: i * 0.07 }}
                    onClick={() => handleSend(q)}
                    className="text-left text-sm text-slate-300 rounded-xl p-4 leading-relaxed hover:text-white transition-colors"
                    style={{
                      background: "linear-gradient(145deg, rgba(255,255,255,0.08) 0%, rgba(255,255,255,0.02) 50%, rgba(99,102,241,0.06) 100%)",
                      backdropFilter: "blur(20px) saturate(1.6)",
                      WebkitBackdropFilter: "blur(20px) saturate(1.6)",
                      boxShadow: [
                        "0 0 0 0.5px rgba(255,255,255,0.12)",
                        "inset 0 1px 0 rgba(255,255,255,0.18)",
                        "inset 0 -1px 0 rgba(0,0,0,0.12)",
                        "0 4px 16px rgba(0,0,0,0.3)",
                      ].join(", "),
                    }}
                  >
                    <Text_03 text={q} className="text-sm" />
                  </motion.button>
                ))}
              </div>
            </motion.div>
          )}
          </div>
        </main>
      </motion.div>
    </>
  );
}
